# Pick a color based on severity value.
def severity_color(severity: float) -> str:
    if severity >= 9:
        return RED
    if severity >= 7:
        return ORANGE
    if severity >= 5:
        return YELLOW
    return GREEN


# Pick a color based on final risk score.
def risk_color(risk_score: float) -> str:
    if risk_score >= 15:
        return RED
    if risk_score >= 10:
        return ORANGE
    if risk_score >= 5:
        return YELLOW
    return GREEN


# Convert risk score into a readable risk band.
def risk_label(risk_score: float) -> str:
    if risk_score >= 15:
        return "CRITICAL"
    if risk_score >= 10:
        return "HIGH"
    if risk_score >= 5:
        return "MEDIUM"
    return "LOW"


# Convert severity value into a readable severity band.
def severity_label(severity: float) -> str:
    if severity >= 9:
        return "CRITICAL"
    if severity >= 7:
        return "HIGH"
    if severity >= 5:
        return "MEDIUM"
    return "LOW"


# Convert long asset names into shorter display names.
def display_asset(asset_target: str) -> str:
    return ASSET_DISPLAY_NAMES.get(str(asset_target), str(asset_target))


# Show whether model prediction matches the actual label.
def prediction_status(predicted_label: str, actual_label: str) -> str:
    return "MATCH" if predicted_label == actual_label else "CHECK"


# Explain why an alert was ranked highly.
def score_reason(p_attack: float, severity: int, asset_value: int) -> str:
    return f"{p_attack:.1%} attack + sev {severity} + asset {asset_value}"


# Pick a color based on Precision@K.
def precision_color(precision: float) -> str:
    if precision >= 0.90:
        return GREEN
    if precision >= 0.70:
        return YELLOW
    return RED


# Load ranked alerts generated by the risk-layer notebook.
def load_alerts(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Alert CSV not found: {path}\n"
            f"Run the risk-layer notebook first, or pass --input /path/to/file.csv."
        )

    df = pd.read_csv(path)
    missing = REQUIRED_ALERT_COLUMNS - set(df.columns)

    if missing:
        missing_list = ", ".join(sorted(missing))
        raise ValueError(f"Alert CSV is missing required columns: {missing_list}")

    return df


# Load Precision@K and Recall@K metrics.
def load_metrics(path: Path) -> pd.DataFrame | None:
    if not path.exists():
        print(color(f"  [!] Metrics file not found: {path}", ORANGE))
        return None

    df = pd.read_csv(path)
    missing = REQUIRED_METRIC_COLUMNS - set(df.columns)

    if missing:
        missing_list = ", ".join(sorted(missing))
        print(color(f"  [!] Metrics CSV missing columns: {missing_list}", ORANGE))
        return None

    return df


# Load optional user config JSON.
def load_config(config_path: Path) -> dict:
    if not config_path.exists():
        raise FileNotFoundError(f"Config file not found: {config_path}")

    with config_path.open("r", encoding="utf-8") as file:
        return json.load(file)


# Apply optional user severity settings from config.
def apply_severity_config(df: pd.DataFrame, config_path: Path) -> pd.DataFrame:
    """
    This only updates severity and risk score using the ranked CSV.
    It does not redo protocol-to-asset mapping because protocol columns are not
    available in the ranked alert CSV.
    """
    cfg = load_config(config_path)
    severity_map = cfg.get("severity_map", {})
    threshold = cfg.get("high_severity_threshold", HIGH_SEVERITY_THRESHOLD)

    if not severity_map:
        print(color(f"  [!] Config has no severity_map: {config_path}", ORANGE))
        return df

    df = df.copy()

    original_predicted = df["predicted_severity"].copy()
    original_actual = df["actual_severity"].copy()

    df["predicted_severity"] = df["predicted_label"].map(severity_map).fillna(original_predicted)
    df["actual_severity"] = df["actual_label"].map(severity_map).fillna(original_actual)

    df["predicted_severity"] = df["predicted_severity"].astype(int)
    df["actual_severity"] = df["actual_severity"].astype(int)

    # Same risk formula as the notebook.
    df["risk_score"] = df["p_malicious"] * (df["predicted_severity"] + df["asset_value"])

    # Recompute high-severity flags using the config threshold.
    df["actual_is_high_severity"] = df["actual_severity"] >= threshold
    df["predicted_is_high_severity"] = df["predicted_severity"] >= threshold

    print(color(f"  [OK] Applied severity config: {config_path.name}", GREEN))
    return df


# Mark predicted high-severity alerts using the notebook threshold.
def prepare_alerts(
    df: pd.DataFrame,
    high_severity_threshold: int = HIGH_SEVERITY_THRESHOLD,
) -> pd.DataFrame:
    df = df.copy()
    df["predicted_is_high_severity"] = df["predicted_severity"] >= high_severity_threshold
    return df


# Sort alerts using the selected ranking method.
def rank_alerts(df: pd.DataFrame, method: str) -> pd.DataFrame:
    column, ascending, _ = RANK_MAP[method]
    return df.sort_values(column, ascending=ascending).reset_index(drop=True)


# Print dataset-level summary.
def print_summary(df: pd.DataFrame) -> None:
    total = len(df)
    malicious = int(df["actual_is_malicious"].sum())
    predicted_high = int(df["predicted_is_high_severity"].sum())
    actual_high = int(df["actual_is_high_severity"].sum())

    divider = color("  " + "=" * 88, CYAN)
    small_divider = color("  " + "-" * 88, DIM)

    print(divider)
    print(color("  DATASET OVERVIEW", BOLD, WHITE))
    print(small_divider)
    print(f"  {'Total alerts loaded':<36} {total:>12,}")
    print(f"  {'Actually malicious alerts':<36} {malicious:>12,}  ({malicious / total * 100:.1f}%)")
    print(f"  {'Predicted high-severity alerts':<36} {predicted_high:>12,}  ({predicted_high / total * 100:.1f}%)")
    print(f"  {'Actually high-severity alerts':<36} {actual_high:>12,}  ({actual_high / total * 100:.1f}%)")
    print(divider)
    print()

    grouped = (
        df.groupby("predicted_label", as_index=False)
        .agg(
            number_of_alerts=("risk_score", "count"),
            avg_p_attack=("p_malicious", "mean"),
            max_severity=("predicted_severity", "max"),
            average_risk_score=("risk_score", "mean"),
            highest_risk_score=("risk_score", "max"),
        )
        .sort_values("highest_risk_score", ascending=False)
        .head(10)
    )

    print(divider)
    print(color("  TOP ATTACK TYPES BY HIGHEST RISK SCORE", BOLD, WHITE))
    print(small_divider)
    print(
        color(
            f"  {'Attack Type':<32} {'Alerts':>10} {'Avg P(Attack)':>15} "
            f"{'Max Sev':>9} {'Avg Risk':>10} {'Max Risk':>10}",
            DIM,
        )
    )
    print(small_divider)

    for row in grouped.itertuples(index=False):
        sev_code = severity_color(row.max_severity)
        risk_code = risk_color(row.highest_risk_score)

        print(
            f"  {color(row.predicted_label, sev_code):<32} "
            f"{row.number_of_alerts:>10,} "
            f"{row.avg_p_attack:>15.1%} "
            f"{color(row.max_severity, sev_code):>9} "
            f"{row.average_risk_score:>10.2f} "
            f"{color(f'{row.highest_risk_score:.2f}', risk_code):>10}"
        )

    print(divider)
    print_formula()


