# Add color to terminal text when colors are enabled.
def color(text, *codes):
    if not USE_COLOR:
        return str(text)
    return "".join(codes) + str(text) + RESET


# Shorten long text so table columns do not break.
def truncate(text: str, width: int) -> str:
    text = str(text)
    if len(text) <= width:
        return text
    if width <= 3:
        return text[:width]
    return text[: width - 3] + "..."


# Format one table cell with optional color.
def cell(text, width: int, align: str = "<", *codes) -> str:
    value = truncate(str(text), width)
    formatted = f"{value:{align}{width}}"
    return color(formatted, *codes) if codes else formatted


